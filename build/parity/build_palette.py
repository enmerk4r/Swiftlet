"""Generate src/Swiftlet.Gh2/Palette.g.cs: the GH1 palette layout for the GH2 Swiftlet tab.

GH1 groups the objects of each panel into rows by GH_Exposure (primary, secondary, ... septenary, then
"last"); GH2 groups them by Nomen.Slot. This writes one lookup from docs/parity.json so every GH2
component and parameter gets the slot of its GH1 row (0 = primary ... 7 = last) and GH1 "hidden"
objects get Rank.Hidden. Keys are the GH2 class name (from the generated gh2 blocks) and, as a
fallback, "section|name" for objects whose GH2 class is not known yet.

    python build/parity/build_palette.py
"""
import json, pathlib

REPO = pathlib.Path(__file__).resolve().parent.parent.parent
ORDER = ["primary", "secondary", "tertiary", "quarternary", "quinary", "senary", "septenary", "last"]


def main():
    entries = json.load(open(REPO / "docs" / "parity.json", encoding="utf-8"))["entries"]
    by_class, by_name = {}, {}
    for e in entries:
        if e["archived"]:
            continue  # archived GH1 objects are hidden in GH2 through [Obsolete] or have no GH2 class
        exposure = e["exposure"]
        hidden = exposure == "hidden"
        slot = 0 if hidden else ORDER.index(exposure)
        value = (slot, "Hidden" if hidden else "Normal")
        if e["gh2"].get("class"):
            by_class[e["gh2"]["class"]] = value
        by_name[f'{e["panel"]}|{e["name"]}'] = value

    def rows(d):
        return "\n".join(f'        ["{k}"] = ({s}, Rank.{r}),' for k, (s, r) in sorted(d.items()))

    text = f"""// <auto-generated>
// Generated by build/parity/build_palette.py from docs/parity.json. Do not edit by hand.
// </auto-generated>
#nullable enable
using Grasshopper2.UI;

namespace Swiftlet.Gh2;

internal static partial class Palette
{{
    /// <summary>GH2 class name -> (slot, rank) from the GH1 exposure of the same object.</summary>
    private static readonly System.Collections.Generic.Dictionary<string, (int Slot, Rank Rank)> ByClass = new(System.StringComparer.Ordinal)
    {{
{rows(by_class)}
    }};

    /// <summary>"section|name" -> (slot, rank), used when a class is not in <see cref="ByClass"/>.</summary>
    private static readonly System.Collections.Generic.Dictionary<string, (int Slot, Rank Rank)> ByName = new(System.StringComparer.Ordinal)
    {{
{rows(by_name)}
    }};
}}
"""
    out = REPO / "src" / "Swiftlet.Gh2" / "Palette.g.cs"
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out} ({len(by_class)} classes, {len(by_name)} names)")


if __name__ == "__main__":
    main()
